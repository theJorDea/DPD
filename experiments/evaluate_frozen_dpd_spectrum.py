"""Evaluate a frozen DPD waveform bundle with a sealed spectral protocol.

The runner is deliberately inference/evaluation-only.  It does not fit a PA,
fit a DPD, estimate gain/delay, select a model, or accept CLI band overrides.
The input archive must already contain paired desired/drive/no-DPD/DPD output
arrays generated by one frozen cascade experiment.

``test`` is reserved for an explicitly released held-out run.  Previously
opened legacy tests use ``legacy_test`` and remain descriptive only.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import secrets
import sys
from typing import Any

import numpy as np

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from baseline.metrics import as_complex, papr_db, peak_amplitude  # noqa: E402
from baseline.spectral_regions import (  # noqa: E402
    SpectralRegion,
    configured_spectral_region_report,
)

SCHEMA_VERSION = 1
REQUIRED_WAVEFORM_KEYS = (
    "desired_input",
    "predistorted_drive",
    "no_dpd_output",
    "dpd_output",
)


def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _declared_path(value: object, *, field: str) -> Path:
    if not isinstance(value, str) or not value:
        raise ValueError(f"{field} must be a non-empty path string")
    path = Path(value)
    if not path.is_absolute():
        path = PROJECT_ROOT / path
    return Path(os.path.abspath(path))


def _require_hash_map(value: object, *, field: str) -> dict[str, str]:
    if not isinstance(value, dict) or not value:
        raise ValueError(f"{field} must be a non-empty object")
    result: dict[str, str] = {}
    for raw_path, raw_hash in value.items():
        path = _declared_path(raw_path, field=f"{field} path")
        if (
            not isinstance(raw_hash, str)
            or len(raw_hash) != hashlib.sha256().digest_size * 2
            or any(char not in "0123456789abcdef" for char in raw_hash)
        ):
            raise ValueError(f"{field} contains an invalid SHA-256")
        result[str(path)] = raw_hash
    return result


def _verify_file_hashes(
    paths_and_hashes: dict[str, str],
    *,
    label: str,
) -> dict[str, str]:
    resolved: dict[str, str] = {}
    for raw_path, expected in paths_and_hashes.items():
        path = Path(raw_path)
        if not path.is_file() or path.is_symlink():
            raise FileNotFoundError(
                f"{label} must be a regular file, not a symlink: {path}"
            )
        actual = file_sha256(path)
        if actual != expected:
            raise ValueError(
                f"{label} SHA-256 mismatch for {path}: "
                f"expected {expected}, found {actual}"
            )
        resolved[str(path)] = actual
    return resolved


def _region_from_config(value: object, *, field: str) -> SpectralRegion:
    if not isinstance(value, dict):
        raise ValueError(f"{field} must be an object")
    if set(value) != {"name", "low_hz", "high_hz"}:
        raise ValueError(f"{field} must contain name, low_hz and high_hz")
    try:
        return SpectralRegion(
            str(value["name"]),
            float(value["low_hz"]),
            float(value["high_hz"]),
        )
    except (TypeError, ValueError) as error:
        raise ValueError(f"{field} is invalid") from error


def validate_config(config: dict[str, Any], *, release_test: bool) -> None:
    """Validate all non-waveform-dependent protocol invariants."""

    if int(config.get("schema_version", -1)) != SCHEMA_VERSION:
        raise ValueError("unsupported spectral runner schema")
    if config.get("task") != "frozen_dpd_spectral_evaluation":
        raise ValueError("config task is not frozen DPD spectral evaluation")
    split_role = config.get("split_role")
    if split_role not in {"validation", "test", "legacy_test", "physical_capture"}:
        raise ValueError("unsupported split_role")
    if split_role == "test" and not release_test:
        raise ValueError("test evaluation requires explicit --release-test")
    if bool(config.get("selection_performed", True)):
        raise ValueError("selection_performed must be false")
    if bool(config.get("fit_performed", True)):
        raise ValueError("fit_performed must be false")
    if bool(config.get("gain_or_alignment_retuned", True)):
        raise ValueError("gain_or_alignment_retuned must be false")

    claim_scope = config.get("claim_scope")
    if not isinstance(claim_scope, dict):
        raise ValueError("claim_scope must be an object")
    if bool(claim_scope.get("rf_harmonic_claim", True)):
        raise ValueError(
            "RF harmonic claims are forbidden without an RF capture contract"
        )
    if split_role == "legacy_test" and not bool(
        claim_scope.get("descriptive_previously_opened_test", False)
    ):
        raise ValueError(
            "legacy_test must be explicitly marked descriptive_previously_opened_test"
        )

    framing = config.get("framing")
    if not isinstance(framing, dict):
        raise ValueError("framing must be an object")
    required_framing = {
        "frame_origin_samples",
        "complete_frames_only",
        "state_reset_policy",
        "crop_policy",
    }
    if set(framing) != required_framing:
        raise ValueError("framing fields are incomplete or have extras")
    if (
        not isinstance(framing["frame_origin_samples"], int)
        or isinstance(framing["frame_origin_samples"], bool)
        or framing["frame_origin_samples"] < 0
    ):
        raise ValueError("frame_origin_samples must be a non-negative integer")
    if framing["complete_frames_only"] is not True:
        raise ValueError("only complete frames are supported")
    if not isinstance(framing["state_reset_policy"], str) or not isinstance(
        framing["crop_policy"], str
    ):
        raise ValueError("framing policies must be strings")

    waveform_keys = config.get("waveform_keys")
    if waveform_keys != {key: key for key in REQUIRED_WAVEFORM_KEYS}:
        raise ValueError("waveform_keys must use the frozen four-key contract")
    _declared_path(config.get("waveform_archive"), field="waveform_archive")
    _require_hash_map(config.get("source_sha256"), field="source_sha256")

    fs_hz = config.get("fs_hz")
    nperseg = config.get("nperseg")
    if (
        not isinstance(fs_hz, (int, float))
        or isinstance(fs_hz, bool)
        or not np.isfinite(float(fs_hz))
        or float(fs_hz) <= 0.0
    ):
        raise ValueError("fs_hz must be positive and finite")
    if (
        not isinstance(nperseg, int)
        or isinstance(nperseg, bool)
        or nperseg < 2
        or nperseg % 2
    ):
        raise ValueError("nperseg must be an even integer >= 2")
    _region_from_config(config.get("main_region"), field="main_region")
    regions = config.get("regions")
    if not isinstance(regions, list) or not regions:
        raise ValueError("regions must be a non-empty list")
    parsed = [
        _region_from_config(region, field=f"regions[{index}]")
        for index, region in enumerate(regions)
    ]
    if len({region.name for region in parsed}) != len(parsed):
        raise ValueError("region names must be unique")
    quantiles = config.get("quantiles", [0.0, 0.5, 0.95, 1.0])
    if (
        not isinstance(quantiles, list)
        or not quantiles
        or any(
            not isinstance(value, (int, float))
            or isinstance(value, bool)
            or not np.isfinite(float(value))
            or not 0.0 <= float(value) <= 1.0
            for value in quantiles
        )
        or any(
            float(left) > float(right)
            for left, right in zip(quantiles, quantiles[1:])
        )
    ):
        raise ValueError("quantiles must be sorted finite values in [0, 1]")


def _load_waveforms(
    archive: Path,
    *,
    nperseg: int,
) -> tuple[dict[str, np.ndarray], dict[str, str]]:
    if not archive.is_file() or archive.is_symlink():
        raise FileNotFoundError("waveform_archive must be a regular file")
    arrays: dict[str, np.ndarray] = {}
    with np.load(archive, allow_pickle=False) as payload:
        if set(payload.files) != {"schema_version", *REQUIRED_WAVEFORM_KEYS}:
            raise ValueError("waveform archive keys do not match frozen contract")
        if int(np.asarray(payload["schema_version"]).item()) != SCHEMA_VERSION:
            raise ValueError("unsupported waveform archive schema")
        for key in REQUIRED_WAVEFORM_KEYS:
            raw_array = np.asarray(payload[key])
            if raw_array.dtype == object or not np.issubdtype(
                raw_array.dtype, np.number
            ):
                raise ValueError(f"{key} must be numeric and non-object")
            array = as_complex(raw_array, name=key)
            if array.ndim < 1 or array.shape[-1] == 0:
                raise ValueError(f"{key} has an invalid shape")
            if array.shape[-1] % nperseg:
                raise ValueError(
                    f"{key} length is not a multiple of nperseg"
                )
            arrays[key] = array.copy()
    shapes = {array.shape for array in arrays.values()}
    if len(shapes) != 1:
        raise ValueError("all waveform arrays must have identical shapes")
    array_hashes = {
        key: hashlib.sha256(
            np.ascontiguousarray(array).view(np.uint8).tobytes()
        ).hexdigest()
        for key, array in arrays.items()
    }
    return arrays, array_hashes


def _finite_record(value: object) -> dict[str, Any]:
    number = float(value)
    if np.isfinite(number):
        return {"value": number, "status": "finite"}
    if np.isnan(number):
        return {"value": None, "status": "not_a_number"}
    return {
        "value": None,
        "status": "positive_infinity" if number > 0 else "negative_infinity",
    }


def _finite_values(values: object) -> list[dict[str, Any]]:
    array = np.asarray(values, dtype=float).reshape(-1)
    return [_finite_record(value) for value in array]


def _summary(
    config: dict[str, Any],
    arrays: dict[str, np.ndarray],
    array_hashes: dict[str, str],
    report: dict[str, Any],
    *,
    config_sha256: str,
    source_hashes: dict[str, str],
) -> dict[str, Any]:
    regions: dict[str, Any] = {}
    for name, row in report["regions"].items():
        regions[name] = {
            "low_hz": float(row["low_hz"]),
            "high_hz": float(row["high_hz"]),
            "no_dpd_welch_spectrum_bin_sum": _finite_record(
                row["no_dpd_integrated_power"]
            ),
            "dpd_welch_spectrum_bin_sum": _finite_record(
                row["dpd_integrated_power"]
            ),
            "no_dpd_dbc": _finite_record(row["no_dpd_dbc"]),
            "dpd_dbc": _finite_record(row["dpd_dbc"]),
            "absolute_suppression_db": _finite_record(
                row["suppression_db"]
            ),
            "relative_leakage_improvement_db": _finite_record(
                row["relative_leakage_improvement_db"]
            ),
            "quantiles": {
                "probabilities": [
                    float(value)
                    for value in row["quantiles"]["probabilities"]
                ],
                "no_dpd_dbc": _finite_values(row["quantiles"]["no_dpd_dbc"]),
                "dpd_dbc": _finite_values(row["quantiles"]["dpd_dbc"]),
                "absolute_suppression_db": _finite_values(
                    row["quantiles"]["suppression_db"]
                ),
                "relative_leakage_improvement_db": _finite_values(
                    row["quantiles"]["relative_leakage_improvement_db"]
                ),
            },
        }
    main = report["main_region"]
    return {
        "schema_version": SCHEMA_VERSION,
        "artifact_type": "frozen_dpd_spectral_evaluation",
        "claims_scope": config["claim_scope"],
        "split_role": config["split_role"],
        "protocol": {
            "fs_hz": float(config["fs_hz"]),
            "nperseg": int(config["nperseg"]),
            "framing": config["framing"],
            "definition": report["definition"],
        },
        "input_provenance": {
            "config_sha256": config_sha256,
            "waveform_archive": str(
                _declared_path(config["waveform_archive"], field="waveform_archive")
            ),
            "waveform_archive_sha256": file_sha256(
                _declared_path(config["waveform_archive"], field="waveform_archive")
            ),
            "waveform_array_sha256": array_hashes,
            "source_sha256": source_hashes,
            "waveform_roles": list(REQUIRED_WAVEFORM_KEYS),
        },
        "signal_summary": {
            "desired_input_peak": peak_amplitude(arrays["desired_input"]),
            "predistorted_drive_peak": peak_amplitude(
                arrays["predistorted_drive"]
            ),
            "predistorted_drive_papr_db": papr_db(
                arrays["predistorted_drive"]
            ),
            "no_dpd_output_peak": peak_amplitude(arrays["no_dpd_output"]),
            "dpd_output_peak": peak_amplitude(arrays["dpd_output"]),
        },
        "main_region": {
            "name": main["name"],
            "low_hz": float(main["low_hz"]),
            "high_hz": float(main["high_hz"]),
            "no_dpd_welch_spectrum_bin_sum": _finite_record(
                main["no_dpd_integrated_power"]
            ),
            "dpd_welch_spectrum_bin_sum": _finite_record(
                main["dpd_integrated_power"]
            ),
            "main_power_change_db": _finite_record(
                main["main_power_change_db"]
            ),
        },
        "regions": regions,
        "frame_count": int(report["frame_count"]),
        "selection_performed": False,
        "fit_performed": False,
        "gain_or_alignment_retuned": False,
    }


def evaluate(
    config_path: str | Path,
    output_dir: str | Path,
    *,
    release_test: bool = False,
) -> dict[str, Any]:
    config_file = Path(config_path).resolve()
    if not config_file.is_file() or config_file.is_symlink():
        raise FileNotFoundError("config must be a regular file")
    config_bytes = config_file.read_bytes()
    config = json.loads(config_bytes.decode("utf-8"))
    if not isinstance(config, dict):
        raise ValueError("config must contain one JSON object")
    validate_config(config, release_test=release_test)

    source_hashes_expected = _require_hash_map(
        config["source_sha256"],
        field="source_sha256",
    )
    source_hashes = _verify_file_hashes(
        source_hashes_expected,
        label="source",
    )
    archive = _declared_path(config["waveform_archive"], field="waveform_archive")
    if not archive.is_file() or archive.is_symlink():
        raise FileNotFoundError("waveform_archive must be a regular file")
    expected_archive_hash = config.get("waveform_archive_sha256")
    if (
        not isinstance(expected_archive_hash, str)
        or len(expected_archive_hash) != 64
    ):
        raise ValueError("waveform_archive_sha256 must be a 64-character hash")
    if file_sha256(archive) != expected_archive_hash:
        raise ValueError("waveform archive SHA-256 mismatch before load")

    arrays, array_hashes = _load_waveforms(
        archive,
        nperseg=int(config["nperseg"]),
    )
    main_region = _region_from_config(config["main_region"], field="main_region")
    regions = tuple(
        _region_from_config(region, field=f"regions[{index}]")
        for index, region in enumerate(config["regions"])
    )
    report = configured_spectral_region_report(
        arrays["no_dpd_output"],
        arrays["dpd_output"],
        fs=float(config["fs_hz"]),
        nperseg=int(config["nperseg"]),
        main_region=main_region,
        regions=regions,
        quantiles=tuple(float(value) for value in config["quantiles"]),
    )
    # Close the input TOCTOU window before publication.
    if file_sha256(archive) != expected_archive_hash:
        raise ValueError("waveform archive changed during evaluation")
    source_hashes = _verify_file_hashes(
        source_hashes_expected,
        label="source",
    )
    output = Path(output_dir).resolve()
    if output.exists() or output.is_symlink():
        raise FileExistsError(f"refusing to overwrite output: {output}")
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.parent / f".{output.name}.tmp-{secrets.token_hex(12)}"
    temporary.mkdir()
    try:
        summary = _summary(
            config,
            arrays,
            array_hashes,
            report,
            config_sha256=hashlib.sha256(config_bytes).hexdigest(),
            source_hashes=source_hashes,
        )
        spectra_arrays: dict[str, np.ndarray] = {
            "frequencies_hz": report["frequencies_hz"],
            "no_dpd_average_power_spectrum": report[
                "no_dpd_average_power_spectrum"
            ],
            "dpd_average_power_spectrum": report[
                "dpd_average_power_spectrum"
            ],
        }
        for index, region in enumerate(regions):
            row = report["regions"][region.name]
            spectra_arrays[f"region_{index}_no_dpd_dbc"] = row["per_frame"][
                "no_dpd_dbc"
            ]
            spectra_arrays[f"region_{index}_dpd_dbc"] = row["per_frame"][
                "dpd_dbc"
            ]
            spectra_arrays[
                f"region_{index}_absolute_suppression_db"
            ] = row["per_frame"]["suppression_db"]
            spectra_arrays[
                f"region_{index}_relative_leakage_improvement_db"
            ] = row["per_frame"]["relative_leakage_improvement_db"]
        spectra_path = temporary / "spectra.npz"
        np.savez_compressed(spectra_path, **spectra_arrays)
        summary_path = temporary / "summary.json"
        summary_path.write_text(
            json.dumps(summary, indent=2, sort_keys=True, allow_nan=False)
            + "\n",
            encoding="utf-8",
        )
        manifest = {
            "schema_version": SCHEMA_VERSION,
            "artifact_type": "frozen_dpd_spectral_evaluation_bundle",
            "config_sha256": summary["input_provenance"]["config_sha256"],
            "input_archive_sha256": expected_archive_hash,
            "source_sha256": source_hashes,
            "artifacts": {
                "summary.json": file_sha256(summary_path),
                "spectra.npz": file_sha256(spectra_path),
            },
            "atomic_publication": True,
            "selection_performed": False,
            "fit_performed": False,
        }
        manifest_path = temporary / "completion_manifest.json"
        manifest_path.write_text(
            json.dumps(manifest, indent=2, sort_keys=True, allow_nan=False)
            + "\n",
            encoding="utf-8",
        )
        os.replace(temporary, output)
        temporary = None  # type: ignore[assignment]
        return summary | {
            "artifacts": {
                "summary": str(output / "summary.json"),
                "spectra": str(output / "spectra.npz"),
                "completion_manifest": str(output / "completion_manifest.json"),
            }
        }
    finally:
        if temporary is not None and temporary.exists():
            for child in temporary.iterdir():
                child.unlink()
            temporary.rmdir()


def _argument_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--release-test", action="store_true")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _argument_parser().parse_args(argv)
    evaluate(args.config, args.output_dir, release_test=args.release_test)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
